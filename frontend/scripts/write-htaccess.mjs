// After a static build, writes out/.htaccess for Apache/LiteSpeed hosting:
// - each dynamic route is exported once as "_"; serve it for every id
// - /api/... (images embedded in lessons) goes to the API server
import { existsSync, writeFileSync } from "node:fs";

if (!existsSync("out")) process.exit(0); // server build, nothing to do

const api = (process.env.NEXT_PUBLIC_API_URL || "http://localhost:3001").replace(/\/+$/, "");
const routes = "(subjects|practice|admin/users)";
const notFile = "RewriteCond %{REQUEST_FILENAME} !-f\nRewriteCond %{REQUEST_FILENAME} !-d";

writeFileSync(
  "out/.htaccess",
  `# Generated by scripts/write-htaccess.mjs
Options -MultiViews
ErrorDocument 404 /404.html
RewriteEngine On

RewriteRule ^api/(.*)$ ${api}/api/$1 [R=302,L]

${notFile}
RewriteRule ^${routes}/[^/]+/?$ $1/_/index.html [L]
${notFile}
RewriteRule ^subjects/[^/]+/(edit|manage)/?$ subjects/_/$1/index.html [L]
${notFile}
RewriteRule ^${routes}/[^/]+/(.+)$ $1/_/$2 [L]
`,
);
console.log(`out/.htaccess written (API: ${api})`);
